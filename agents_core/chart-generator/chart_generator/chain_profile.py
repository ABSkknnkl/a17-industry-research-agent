def subject_entity(subject: str) -> str:
    """从主题里抽出「被研究的**那一家**公司/主体」，抽不出就返回 ""。

    动机（2026-10-21，run-20261021183219 实测）：主题「宇树科技机器人」，
    出来的 22 节点图里**「宇树」只出现在标题**——画的是通用工业机器人，主角缺席。
    这里做确定性抽取，交给 ``strengthen_brand_card`` 强制挂进品牌卡，
    不再依赖 LLM 是否"记得"写它。

    例：``宇树科技机器人`` → ``宇树科技``；``宁德时代产业链`` → ``宁德时代``；
    ``工业机器人`` / ``手机`` / ``低空经济`` → ``""``（行业主题，无单一主体）。
    """
    s = str(subject or "").strip()
    if not s:
        return ""
    # 🔴 守卫（2026-10-21 实测踩坑）：`_profile_subject(top)` 会拼出
    # "标题 核心产品" 这种伪主题（含空格、长度很长），旧版把它整串当成公司名，
    # 于是品牌卡被补进「t  x」「产业链图谱 通用硬件」这类垃圾 → 测试直接红。
    # 公司名不含空格、不会很长，也不含这些结构词。
    if any(ch.isspace() for ch in s) or len(s) > 12:
        return ""
    if any(w in s for w in ("图谱", "全景", "结构", "产业链", "供应链", "产业链图谱")):
        return ""
    # ① 去产业后缀（可叠：宁德时代产业链上的…）
    for suf in ("产业链", "供应链", "价值链", "赛道", "板块", "概念", "行业", "产业"):
        if s.endswith(suf) and len(s) - len(suf) >= 2:
            s = s[: -len(suf)]
    # ② 去尾部括号补充（「半导体设备（刻蚀/沉积）」→「半导体设备」）
    s = re.sub(r"[（(][^）)]*[）)]\s*$", "", s).strip()
    # ③ 去品类词（只剥一层，且剥完不能只剩泛修饰词）
    for suf in ("机器人", "机械臂", "机械手", "设备", "装备", "整机", "材料",
                "器件", "模组", "系统", "芯片"):
        if s.endswith(suf) and len(s) - len(suf) >= 2:
            s = s[: -len(suf)]
            break
    # ④ 去尾部泛修饰词（可叠：「宇树科技人形」→「宇树科技」）。
    # 2026-10-21 实测：旧版只按 _SUBJECT_GENERIC_TAILS 整串比对，剥完还剩
    # 「宇树科技人形」这种半截词，被当成公司名写进品牌卡。
    for _ in range(2):
        for modifier in ("人形", "四足", "双足", "协作", "智能", "工业", "消费",
                         "商用", "高端", "新型", "通用", "专业"):
            if s.endswith(modifier) and len(s) - len(modifier) >= 2:
                s = s[: -len(modifier)]
                break
        else:
            break
    s = s.strip()
    if len(s) < 2:
        return ""
    if s in _SUBJECT_GENERIC_TAILS:
        return ""
    if s in ("工业", "消费", "商用", "智能", "高端", "新型", "全球", "国内",
             "中国", "海外", "国产", "通用", "专业", "人形", "四足", "双足",
             "协作", "大型", "小型", "微型", "传统", "先进", "现代"):
        return ""
    # ③ 与画像关键词完全重合 → 是行业名不是公司名
    try:
        for prof in _PROFILES:
            if s in (prof.get("kw") or ()):
                return ""
    except Exception:                        # pragma: no cover
        pass
    # ④ 与**结构骨架**的行业词重合 → 同样是行业名。2026-10-22 补：
    #    「白酒/钢铁/快递/SaaS」这类主题**没有专属画像**（落 generic），
    #    旧实现只查画像 kw，查不到就把主题本身当公司名返回，
    #    于是 `strengthen_brand_card` 把「白酒」当成一家公司补进品牌卡
    #    （实测 run-20261022111644 品牌卡出现一个叫"白酒"的"品牌"）。
    try:
        from chart_generator.chain_structure import STRUCTURES

        for st in STRUCTURES:
            if s in st.signal_words:
                return ""
    except Exception:                        # pragma: no cover
        pass
    # ⑤ 是**产品/品类词**而不是公司名 → 返回空。2026-10-25 补（P1 根治）：
    #    「笔记本电脑」既不在画像 kw、也不在结构信号词里，前四条守卫全部漏网，
    #    于是被补进品牌卡，图上出现一家叫"笔记本电脑"的公司。
    #    改用知识底座的 9.5 万产品词做通用判据（完全相等才判，不做相似匹配）。
    try:
        from chart_generator.chain_kb import is_product_word

        if is_product_word(s):
            return ""
    except Exception:                        # pragma: no cover
        pass
    return s


