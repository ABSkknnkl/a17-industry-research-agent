def _bigrams(s: str) -> set[str]:
    s = str(s or "")
    if len(s) < 2:
        return {s} if s else set()
    return {s[i:i + 2] for i in range(len(s) - 1)}


def match_mid_card(label: str, mid_cards: list) -> str:
    """节点名 → 命中的 canonical 能力卡标题（完全相同优先，其次 2-gram 重叠 ≥0.5）。"""
    lab = str(label or "").strip()
    if not lab:
        return ""
    titles = [c[0] if isinstance(c, (list, tuple)) else str(c) for c in (mid_cards or [])]
    if lab in titles:
        return lab
    a = _bigrams(lab)
    if not a:
        return ""
    best, best_score = "", 0.0
    for t in titles:
        b = _bigrams(t)
        if not b:
            continue
        score = len(a & b) / min(len(a), len(b))
        if score > best_score:
            best, best_score = t, score
    return best if best_score >= 0.5 else ""


def anchor_match(company: str, subject: str, label: str,
                 key_products: list[str] | None = None) -> bool:
    """F10：该公司的角色锚点是否命中这个环节。

    锚点值支持 "/" 分隔的等价说法（「相机/CMOS/传感器/载荷」命中任一即算）。
    匹配范围 = 节点 label + 该节点的 key_products（细分品类常常比环节名更具体）。
    """
    kw = str(role_anchor(subject).get(str(company).strip()) or "")
    if not kw:
        return False
    hay = " ".join([str(label or "")] + [str(x) for x in (key_products or [])])
    return any(part and part in hay for part in kw.split("/"))


