def wrong_fit_hits(label: str, companies: list[str], subject: str) -> list[str]:
    """F12：返回该节点上「主业与环节不符」的公司名列表。

    现有裁判只校验可追溯性与结构，不回答"这家公司是不是干这个环节的"，
    于是激光雷达图出现了「芯片代工＝长鑫科技」「监管与注册＝泰格医药」这类错配。
    """
    wf = wrong_fit_map(subject)
    if not wf:
        return []
    lab = str(label or "")
    hits: list[str] = []
    for kw, banned in wf.items():
        if kw not in lab:
            continue
        for c in companies or []:
            name = str(c).strip()
            if not name:
                continue
            if any(b in name or name in b for b in banned):
                if name not in hits:
                    hits.append(name)
    return hits


def brand_card_violations(top: dict, subject: str) -> list[str]:
    """F8 验收断言：品牌卡上出现的「上游角色」公司（不该在品牌卡）。"""
    base = set(upstream_leaders(subject))
    if not base:
        return []
    nodes = [n for n in (top.get("nodes") or []) if isinstance(n, dict)]
    core = next((n for n in nodes if n.get("is_core")), None)
    if core is None:
        return []
    comps = [str(c).strip() for c in (core.get("companies") or []) if str(c).strip()]
    return [c for c in comps if c in base]


def brand_scope_warnings(top: dict, subject: str) -> list[str]:
    """F14 验收告警（不阻断）：品牌卡上出现了**本细分之外**的厂商。

    例：标题写「半导体设备（刻蚀/沉积）」，品牌卡却出现盛美上海（清洗）、
    华海清科（CMP）——不算错，但会让标题与卡片范围不一致，出图前应提示。
    """
    prof = detect_profile(subject)
    scope_key = str(prof.get("scope_key") or "")
    scoped = set(prof["leading_brand"])
    if not scope_key or not scoped:
        return []
    # 基础画像（不限细分）的完整名单里、但不在本细分名单里的厂商 = 越界
    base_all = set()
    for p in _PROFILES:
        if p["key"] == prof["key"]:
            base_all = set(p["leading_brand"])
            break
    out_scoped = base_all - scoped
    if not out_scoped:
        return []
    nodes = [n for n in (top.get("nodes") or []) if isinstance(n, dict)]
    core = next((n for n in nodes if n.get("is_core")), None)
    if core is None:
        return []
    comps = [str(c).strip() for c in (core.get("companies") or []) if str(c).strip()]
    return [c for c in comps if c in out_scoped]


def _as_line(value: Any) -> str:
    """画像字段可能是 list（新写法）或 str（旧写法/消费级修饰）→ 统一成顿号串。"""
    if isinstance(value, (list, tuple)):
        return "、".join(str(v) for v in value if str(v).strip())
    return str(value or "")


